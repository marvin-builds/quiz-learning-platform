#!/usr/bin/env node
// Writes `<dir>/_headers` (default `dist`) after `expo export -p web`: the
// security headers Cloudflare Pages sends for every path of the web app. The
// Content-Security-Policy names the Supabase origin the bundle was built with,
// so EXPO_PUBLIC_SUPABASE_URL is resolved the way `expo export` resolves it
// (production mode, whatever NODE_ENV is): the process environment, then
// `.env.production.local`, `.env.local`, `.env.production`, `.env`.
//
// A later host (e.g. an error-reporting ingest) goes into connect-src here.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const VARIABLE = 'EXPO_PUBLIC_SUPABASE_URL';
const ENV_FILES = ['.env.production.local', '.env.local', '.env.production', '.env'];
const PERMISSIONS = [
  'camera',
  'microphone',
  'geolocation',
  'payment',
  'usb',
  'serial',
  'hid',
  'midi',
  'accelerometer',
  'gyroscope',
  'magnetometer',
];

function fail(message) {
  console.error(`security-headers: ${message}`);
  process.exit(1);
}

// The value of `name` in a dotenv file, or undefined when it doesn't set it.
function readEnvFile(file, name) {
  if (!existsSync(file)) return undefined;
  let value;
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const match = /^\s*(?:export\s+)?([\w.-]+)\s*=\s*(.*?)\s*$/.exec(line);
    if (match?.[1] !== name) continue;
    const raw = match[2];
    const quoted = /^(['"`])(.*)\1$/.exec(raw);
    value = quoted ? quoted[2] : raw.replace(/\s+#.*$/, '');
  }
  return value;
}

function supabaseUrl() {
  if (process.env[VARIABLE] !== undefined) return process.env[VARIABLE];
  for (const file of ENV_FILES) {
    const value = readEnvFile(path.resolve(file), VARIABLE);
    if (value !== undefined) return value;
  }
  return undefined;
}

function supabaseOrigin() {
  const value = supabaseUrl();
  if (!value) fail(`${VARIABLE} is not set (process environment or .env files)`);
  let url;
  try {
    url = new URL(value);
  } catch {
    fail(`${VARIABLE} is no URL: ${value}`);
  }
  if (url.protocol !== 'http:' && url.protocol !== 'https:') {
    fail(`${VARIABLE} must be an http(s) URL: ${value}`);
  }
  return url;
}

// sha256 sources for the inline scripts the browser runs in index.html.
function inlineScriptHashes(dir) {
  const file = path.join(dir, 'index.html');
  if (!existsSync(file)) return [];
  const html = readFileSync(file, 'utf8');
  return [...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)]
    .filter(([, attributes]) => !/\bsrc=/.test(attributes))
    .filter(([, attributes]) => {
      const type = /\btype=["']?([^"'\s>]+)/.exec(attributes)?.[1]?.toLowerCase();
      return !type || type === 'module' || /javascript|ecmascript/.test(type);
    })
    .map(([, , body]) => body)
    .filter((body) => body.trim() !== '')
    .map((body) => `'sha256-${createHash('sha256').update(body).digest('base64')}'`);
}

function contentSecurityPolicy(supabase, scriptHashes) {
  const websocket = `${supabase.protocol === 'https:' ? 'wss' : 'ws'}://${supabase.host}`;
  const directives = [
    ["default-src 'self'"],
    ["script-src 'self'", ...new Set(scriptHashes)],
    // react-native-web inserts <style> elements at run time.
    ["style-src 'self' 'unsafe-inline'"],
    ["img-src 'self' data: blob:", supabase.origin],
    // blob: because the web upload fetches the picked file's blob: URL.
    ["connect-src 'self'", supabase.origin, websocket, 'blob:'],
    ["object-src 'none'"],
    ["base-uri 'self'"],
    ["form-action 'self'"],
    ["frame-ancestors 'none'"],
  ];
  return directives.map((parts) => parts.join(' ')).join('; ');
}

const dir = path.resolve(process.argv[2] ?? 'dist');
const supabase = supabaseOrigin();
const headers = {
  'Content-Security-Policy': contentSecurityPolicy(supabase, inlineScriptHashes(dir)),
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': PERMISSIONS.map((feature) => `${feature}=()`).join(', '),
};

const lines = [
  '# Generated by scripts/security-headers.mjs after the web export; do not edit.',
  '/*',
  ...Object.entries(headers).map(([name, value]) => `  ${name}: ${value}`),
];
writeFileSync(path.join(dir, '_headers'), `${lines.join('\n')}\n`);
console.log(`security-headers: wrote ${path.relative(process.cwd(), path.join(dir, '_headers'))}`);
